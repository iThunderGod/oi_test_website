export function difficultyClass(difficulty) {
  const rank = difficultyRankMap[difficulty] || 1
  if (rank <= 2) return 'easy'
  if (rank <= 4) return 'medium'
  if (rank <= 6) return 'hard'
  return 'challenge'
}

export function findProblem(id) {
  return problems.find((problem) => problem.id === id)
}
